    def _get_fit_seg_flag(self, grid_idxs):
        """
        Returns the response according the participants' final segmentation map

        Parameters:
        ------------
        grid_idxs : list
            the index of the point in the trial grid

        """
        unravel_idx = lambda x: np.asarray(
            np.unravel_index(x - 1, self.fit_segmap.shape[:2])
        ).T

        idx_a = unravel_idx(grid_idxs[0])
        idx_b = unravel_idx(grid_idxs[1])
        seg_flag_a = self.fit_segmap[idx_a[0], idx_a[1]]
        seg_flag_b = self.fit_segmap[idx_b[0], idx_b[1]]

        return seg_flag_a == seg_flag_b

    def _get_fit_psame(self, grid_idxs):
        """
        Returns the segment probabilities decoded from participant responses
        """
        unravel_idx = lambda x: np.asarray(
            np.unravel_index(x - 1, self.fit_segmap.shape[:2])
        ).T

        vec_a = self.fit_pmap[
            :, unravel_idx(grid_idxs[0])[0], unravel_idx(grid_idxs[0])[1]
        ]
        vec_b = self.fit_pmap[
            :, unravel_idx(grid_idxs[1])[0], unravel_idx(grid_idxs[1])[1]
        ]

        psame = np.dot(vec_a, vec_b)

        return psame

    def sample_pmap(self, resize=True):
        """
        Draw a sample from the probabilistic segmentation map decoded from participant responses
        """
        assert hasattr(self, "fit_pmap")
        _sample_pmap = lambda x: np.random.choice(list(range(len(x))), size=1, p=x)

        stop = -1
        # Sample so that every segment is assigned to atleast one pixel
        while stop < 0:
            present = 0
            sample = np.apply_along_axis(_sample_pmap, 0, self.fit_pmap).squeeze()
            for value in range(self.kSeg):
                if value in sample:
                    present += 1
            if present < self.kSeg:
                stop = -1
            else:
                stop = 0

        if resize:
            sample = tb.scale_im_up(sample, self.image.shape[0])
        return sample

