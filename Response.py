        def _sweep(
            self,
            value,
            col="automult",
            conv_failure="argmax",
            mode="base",
            use_boundary=none,
        ):
            """
            parameters:
            -----------
            value : float
            col : str
                "automult" : derivative parameter for flexmm model
                "online_bound": bound parameter for flexmm model
                "ei_bound": bound parameter for vanilla ei model
                "wei_bound" : bound parameter for weighted ei model

            returns:
            ---------
            rts : array of reaction times
            """
            if mode == "base":
                assert hasattr(self, "basemodel")

                if col == "automult":
                    if use_boundary is not none:
                        rts = self.basemodel._get_rt_from_deriv(
                            value,
                            return_mean=true,
                            failure_mode=conv_failure,
                            use_boundary=use_boundary,
                        )
                    else:
                        rts = self.basemodel._get_rt_from_deriv(
                            value, return_mean=true, failure_mode=conv_failure
                        )
                if col == "online_rt":
                    rts = self.basemodel._get_rt_from_boundary(
                        value, param="logits", return_mean=true
                    )
                elif col == "ei_rt":
                    rts = self.basemodel._get_rt_from_boundary(
                        value, param="ei_logits", return_mean=true
                    )
                elif col == "wei_rt":
                    rts = self.basemodel._get_rt_from_boundary(
                        value, param="wei_logits", return_mean=true
                    )
            else:
                if col == "automult":
                    if use_boundary is not none:
                        rts = dynamics._get_rt_from_deriv(
                            self.smooth_logits,
                            self.logit_deriv,
                            value,
                            return_mean=true,
                            failure_mode=conv_failure,
                            mean_axis=(0, -1),
                            use_boundary=use_boundary,
                        )
                    else:
                        rts = dynamics._get_rt_from_deriv(
                            self.smooth_logits,
                            self.logit_deriv,
                            value,
                            return_mean=true,
                            failure_mode=conv_failure,
                            mean_axis=(0, -1),
                        )
                if col == "online_rt":
                    rts = dynamics._get_rt_from_boundary(
                        self.logits,
                        value,
                        return_mean=true,
                        output_flat=false,
                        mean_axis=(0, -1),
                    )
                elif col == "ei_rt":
                    rts = dynamics._get_rt_from_boundary(
                        self.ei_logits,
                        value,
                        return_mean=true,
                        output_flat=false,
                        mean_axis=(0, -1),
                    )
                elif col == "wei_rt":
                    rts = dynamics._get_rt_from_boundary(
                        self.wei_logits,
                        value,
                        return_mean=true,
                        output_flat=false,
                        mean_axis=(0, -1),
                    )

            return rts

